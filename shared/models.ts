/**
 * 探針判定「此模型的 payload 是否用到提示詞」：丟圖即得類（修復/去背/放大/補幀/轉錄）
 * 的 input 完全不吃 prompt——UI 據此把提示詞欄設為選填、後端據此放行空提示詞。
 */
export function modelUsesPrompt(m: ModelEntry): boolean {
  try {
    return JSON.stringify(m.input("__PROBE__", "16:9", "https://probe.example/src")).includes("__PROBE__");
  } catch {
    return true; // 探針失敗保守當「需要提示詞」
  }
}

